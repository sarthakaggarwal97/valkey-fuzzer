#!/usr/bin/env python3
"""Keep docs/components/ in step with the installed component catalog.

The component reference is hand-written prose with two generated tables in
``docs/components/README.md``:

- the index between the ``index`` markers: one row per component and provider
  of the catalog, grouped by role, linking to its section on the group's page,
  with its deployment modes from the catalog. The ``Does`` text, and a note in
  parentheses after the modes, are kept from the row the file already has, so
  a new component needs its row written once by hand (this script says which);
- the declarations table between the ``declarations`` markers: what each
  component publishes, emits, and changes.

It also checks that every catalog component and provider has a ``## `<id>```
section on its group's page and that no page documents an id the catalog
lacks.

    python scripts/gen_component_docs.py          # rewrite the tables
    python scripts/gen_component_docs.py --check  # exit 1 if anything would change (CI)

``tests/test_docs_declarations.py`` runs the check.
"""

import argparse
import difflib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs" / "components"
INDEX = DOCS / "README.md"
INDEX_BEGIN = "<!-- BEGIN index: generated by scripts/gen_component_docs.py -->"
INDEX_END = "<!-- END index -->"
DECLARATIONS_BEGIN = "<!-- BEGIN declarations: generated by scripts/gen_component_docs.py -->"
DECLARATIONS_END = "<!-- END declarations -->"

# Role (the second word of an id) to the page that documents it, in index order.
GROUPS = (
    ("capability", "Capabilities", "capabilities"),
    ("workload", "Workloads", "workloads"),
    ("action", "Actions", "actions"),
    ("fault", "Faults", "faults"),
    ("observer", "Observers", "observers"),
    ("oracle", "Oracles", "oracles"),
    ("artifact", "Providers", "providers"),
    ("resource", "Providers", "providers"),
)
PAGE_OF_ROLE = {role: page for role, _, page in GROUPS}

_ROW = re.compile(r"^\| \[`(?P<id>[^`]+)`\]\([^)]*\) \| (?P<modes>[^|]*) \| (?P<does>.*) \|$")
_SECTION = re.compile(r"^## `([^`]+)`$", re.M)


class DocsError(Exception):
    """The docs cannot be brought in step without a hand-written change."""


def anchor(component_id: str) -> str:
    """GitHub's anchor for a ``## `<id>``` heading: letters, digits, and hyphens of the id."""

    return re.sub(r"[^a-z0-9-]", "", component_id.lower())


def _catalog():
    """``(id, role, modes)`` for every component and provider, in index order."""

    from valkey_fuzzer.components import ENVIRONMENT_PROVIDERS, component_registrations

    entries = []
    for registration in component_registrations():
        modes = registration.deployment_modes
        entries.append((registration.component_id, "any" if modes is None else ", ".join(modes)))
    for provider in ENVIRONMENT_PROVIDERS:
        entries.append((provider.provider_id, provider.kind.value))
    order = {role: position for position, (role, _, _) in enumerate(GROUPS)}

    def key(entry):
        role = entry[0].split(".")[1]
        if role not in order:
            raise DocsError(f"{entry[0]}: role {role!r} has no page; add it to GROUPS in {Path(__file__).name}")
        return (order[role], entry[0])

    return sorted(entries, key=key)


def _between(text: str, begin: str, end: str, path: Path) -> str:
    if begin not in text or end not in text:
        raise DocsError(f"{path}: markers {begin!r} and {end!r} not found")
    return text.split(begin, 1)[1].split(end, 1)[0]


def _replace_between(text: str, begin: str, end: str, body: str) -> str:
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    return f"{head}{begin}\n{body}\n{end}{tail}"


def _existing_rows(index_text: str) -> dict:
    """Each documented id to ``(modes cell, does cell)`` as the index has it now."""

    rows = {}
    for line in index_text.splitlines():
        match = _ROW.match(line)
        if match:
            rows[match.group("id")] = (match.group("modes").strip(), match.group("does").strip())
    return rows


def index_table(catalog, existing: dict) -> str:
    """The grouped index: a heading, a sentence, and a table for each page."""

    missing = [component_id for component_id, _ in catalog if component_id not in existing]
    if missing:
        rows = "\n".join(
            f"| [`{component_id}`]({PAGE_OF_ROLE[component_id.split('.')[1]]}.md#{anchor(component_id)}) "
            f"| {modes} | <what it does, in one line> |"
            for component_id, modes in catalog
            if component_id in missing
        )
        raise DocsError(f"no index row for {', '.join(missing)}; add to {INDEX.relative_to(ROOT)}:\n{rows}")
    stale = sorted(set(existing) - {component_id for component_id, _ in catalog})
    if stale:
        raise DocsError(f"the index lists {', '.join(stale)}, which the catalog lacks; remove the row(s)")

    parts = []
    for role, title, page in GROUPS:
        rows = [(component_id, modes) for component_id, modes in catalog if component_id.split(".")[1] == role]
        if not rows:
            continue
        if parts and parts[-1][0] == title:
            parts[-1][1].extend(rows)
        else:
            parts.append((title, rows, page))
    sections = []
    for title, rows, page in parts:
        column = "Kind" if page == "providers" else "Modes"
        table = [f"### [{title}]({page}.md)", "", f"| Component | {column} | Does |", "| --- | --- | --- |"]
        for component_id, modes in rows:
            old_modes, does = existing[component_id]
            note = old_modes[len(modes) :].strip() if old_modes.startswith(modes) else ""
            if note and not (note.startswith("(") and note.endswith(")")):
                raise DocsError(
                    f"{component_id}: the modes cell {old_modes!r} does not start with the catalog's {modes!r}"
                )
            if not note and old_modes != modes:
                raise DocsError(
                    f"{component_id}: the modes cell {old_modes!r} does not start with the catalog's {modes!r}"
                )
            cell = f"{modes} {note}".strip()
            table.append(f"| [`{component_id}`]({page}.md#{anchor(component_id)}) | {cell} | {does} |")
        sections.append("\n".join(table))
    return "\n\n".join(sections)


def _names(names, many=()) -> str:
    rendered = [f"`{name.replace('{id}', '<id>')}`" + (" (many)" if name in many else "") for name in sorted(names)]
    return "<br>".join(rendered) or "none"


def declarations_table() -> str:
    """What every component declares it publishes, emits, and changes, by id."""

    from valkey_fuzzer.components import component_registrations

    rows = ["| Component | Publishes | Emits | Changes |", "| --- | --- | --- | --- |"]
    for registration in sorted(component_registrations(), key=lambda item: item.component_id):
        declares = registration.declares
        many = {name for name, item in declares.evidence.items() if item.many}
        rows.append(
            f"| `{registration.component_id}` | {_names(declares.events)} | {_names(declares.evidence, many)} "
            f"| {_names(declares.changes)} |"
        )
    return "\n".join(rows)


def check_sections(catalog) -> list:
    """Problems with the group pages: a component without a section, or a section for an unknown id."""

    problems = []
    documented = {}
    for page in sorted({page for _, _, page in GROUPS}):
        path = DOCS / f"{page}.md"
        if not path.exists():
            problems.append(f"{path.relative_to(ROOT)} is missing")
            continue
        for component_id in _SECTION.findall(path.read_text(encoding="utf-8")):
            documented.setdefault(component_id, []).append(page)
    for component_id, _ in catalog:
        page = PAGE_OF_ROLE[component_id.split(".")[1]]
        pages = documented.get(component_id, [])
        if page not in pages:
            problems.append(f"{component_id}: no `## `{component_id}`` section in docs/components/{page}.md")
        for other in pages:
            if other != page:
                problems.append(f"{component_id}: documented in docs/components/{other}.md, its page is {page}.md")
    known = {component_id for component_id, _ in catalog}
    for component_id, pages in sorted(documented.items()):
        if component_id not in known:
            problems.append(f"docs/components/{pages[0]}.md documents {component_id}, which the catalog lacks")
    return problems


def render(index_text: str) -> str:
    """``index_text`` with both generated tables brought in step with the catalog."""

    catalog = _catalog()
    problems = check_sections(catalog)
    if problems:
        raise DocsError("\n".join(problems))
    existing = _existing_rows(_between(index_text, INDEX_BEGIN, INDEX_END, INDEX))
    text = _replace_between(index_text, INDEX_BEGIN, INDEX_END, index_table(catalog, existing))
    return _replace_between(text, DECLARATIONS_BEGIN, DECLARATIONS_END, declarations_table())


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Regenerate the generated tables of docs/components/README.md")
    parser.add_argument("--check", action="store_true", help="Change nothing; exit 1 if the docs are out of step")
    args = parser.parse_args(argv)
    sys.path.insert(0, str(ROOT))
    current = INDEX.read_text(encoding="utf-8")
    try:
        wanted = render(current)
    except DocsError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if wanted == current:
        print(f"{INDEX.relative_to(ROOT)} is in step with the catalog")
        return 0
    if args.check:
        diff = difflib.unified_diff(
            current.splitlines(keepends=True), wanted.splitlines(keepends=True), "README.md", "generated"
        )
        sys.stdout.writelines(diff)
        print(f"error: run python {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
        return 1
    INDEX.write_text(wanted, encoding="utf-8")
    print(f"rewrote the generated tables of {INDEX.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
