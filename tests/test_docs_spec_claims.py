"""The runtime-check tables in docs/spec-bridge.md and each formal/*/README.md list every property of every
bundle's ``claims.yaml``, and say which are evaluated against a live run and which are checked by the model only.

On a mismatch the assertion message holds the table to paste between the markers.
"""

from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "<!-- BEGIN runtime checks: generated by tests/test_docs_spec_claims.py -->"
END = "<!-- END runtime checks -->"
MODEL_ONLY = "no, model only"
ELECTION = "valkey.oracle.cluster-election-safety"
# shortcut: written by hand, because claims.yaml has no field for it; add one if a fifth bundle appears.
RUNTIME = {
    "cluster-election": {
        "OneWinnerPerEpoch": f"yes: `{ELECTION}` and `spec conform`",
        "VoteOncePerEpoch": f"yes: `{ELECTION}` and `spec conform`",
        "VotesSavedBeforeSent": f"yes: `{ELECTION}` (exact, from the `nodes.conf` read at each crash)",
        "NoVoteLostInCrash": "yes: `spec conform`",
    },
    "replication": {"OneHistoryPerId": MODEL_ONLY, "ReplicaIsPrefix": MODEL_ONLY},
    "persistence": {"ManifestFilesExist": MODEL_ONLY, "AofIsPrefix": MODEL_ONLY, "AckedRestored": MODEL_ONLY},
    "slot-migration": {"OneWriter": MODEL_ONLY, "NoAckedWriteLost": MODEL_ONLY},
}
BUNDLES = sorted(path.parent.name for path in (ROOT / "formal").glob("*/claims.yaml"))


def _claims(bundle: str) -> dict:
    return yaml.safe_load((ROOT / "formal" / bundle / "claims.yaml").read_text(encoding="utf-8"))


def bundle_table(bundle: str) -> str:
    rows = ["| Property | Checked against a live run |", "| --- | --- |"]
    for item in _claims(bundle)["properties"]:
        rows.append(f"| `{item['name']}` | {RUNTIME[bundle][item['name']]} |")
    return "\n".join(rows)


def all_bundles_table() -> str:
    rows = ["| Bundle | Claims | Property | Checked against a live run |", "| --- | --- | --- | --- |"]
    for bundle in BUNDLES:
        status = _claims(bundle)["status"]
        for item in _claims(bundle)["properties"]:
            rows.append(f"| `{bundle}` | {status} | `{item['name']}` | {RUNTIME[bundle][item['name']]} |")
    return "\n".join(rows)


def _documented(path: Path) -> str:
    return path.read_text(encoding="utf-8").split(BEGIN, 1)[1].split(END, 1)[0].strip()


def test_the_runtime_check_notes_name_exactly_the_claimed_properties():
    assert set(RUNTIME) == set(BUNDLES)
    for bundle in BUNDLES:
        assert set(RUNTIME[bundle]) == {item["name"] for item in _claims(bundle)["properties"]}, bundle


def test_the_spec_bridge_page_lists_every_property_and_what_checks_it():
    documented = _documented(ROOT / "docs" / "spec-bridge.md")

    assert documented == all_bundles_table(), "regenerate the table:\n" + all_bundles_table()


@pytest.mark.parametrize("bundle", BUNDLES)
def test_each_bundle_readme_lists_its_properties_and_what_checks_them(bundle):
    documented = _documented(ROOT / "formal" / bundle / "README.md")

    assert documented == bundle_table(bundle), "regenerate the table:\n" + bundle_table(bundle)


def test_a_bundle_the_runtime_does_not_check_says_so_in_its_claims():
    # The claims file is the first thing a maintainer reads: it must not suggest a live check that is not there.
    for bundle in BUNDLES:
        text = (ROOT / "formal" / bundle / "claims.yaml").read_text(encoding="utf-8")
        has_runtime_check = any(not note.startswith("no") for note in RUNTIME[bundle].values())
        assert ("Model only:" in text) == (not has_runtime_check), bundle
