"""The runtime-check tables in docs/spec-bridge.md and each formal/*/README.md list every property of every
bundle's ``claims.yaml``, and say which are evaluated against a live run and which are checked by the model only;
and each README's "Files" table names every negative control of ``claims.yaml`` with the property it must violate.

On a mismatch the assertion message holds the table to paste between the markers.
"""

import re
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "<!-- BEGIN runtime checks: generated by tests/test_docs_spec_claims.py -->"
END = "<!-- END runtime checks -->"
MODEL_ONLY = "no, model only"
ELECTION = "valkey.oracle.cluster-election-safety"
# shortcut: written by hand, because claims.yaml names no oracle: the oracle that checks a property on a live run,
# by (bundle, property), and how a check works. Whether `spec conform` checks a property comes from its `conform`.
ORACLE = {
    ("cluster-election", "OneWinnerPerEpoch"): f"`{ELECTION}`",
    ("cluster-election", "VoteOncePerEpoch"): f"`{ELECTION}`",
    ("cluster-election", "VotesSavedBeforeSent"): f"`{ELECTION}`",
}
HOW = {
    ("cluster-election", "VotesSavedBeforeSent"): " (exact, from the `nodes.conf` read at each crash)",
    ("replication", "SameOffsetSameData"): " (from the trace's INFO replication and `DEBUG DIGEST` samples)",
}
BUNDLES = sorted(path.parent.name for path in (ROOT / "formal").glob("*/claims.yaml"))
_CONTROL_ROW = re.compile(r"^\| (?P<files>[^|]*) \| (?P<holds>[^|]*must violate[^|]*) \|$")
_CONTROL_FILE = re.compile(r"`(?:negative-controls/)?([^`./]+)\.(?:cfg|tla)`")  # a row may list two files


def _claims(bundle: str) -> dict:
    return yaml.safe_load((ROOT / "formal" / bundle / "claims.yaml").read_text(encoding="utf-8"))


def runtime_check(bundle: str, item: dict) -> str:
    """What checks a claimed property against a live run: its oracle, `spec conform` (``conform: true``), or nothing."""

    checks = [ORACLE[bundle, item["name"]]] if (bundle, item["name"]) in ORACLE else []
    if item.get("conform") is True:
        checks.append("`spec conform`")
    if not checks:
        return MODEL_ONLY
    return "yes: " + " and ".join(checks) + HOW.get((bundle, item["name"]), "")


def bundle_table(bundle: str) -> str:
    rows = ["| Property | Checked against a live run |", "| --- | --- |"]
    for item in _claims(bundle)["properties"]:
        rows.append(f"| `{item['name']}` | {runtime_check(bundle, item)} |")
    return "\n".join(rows)


def all_bundles_table() -> str:
    rows = ["| Bundle | Claims | Property | Checked against a live run |", "| --- | --- | --- | --- |"]
    for bundle in BUNDLES:
        status = _claims(bundle)["status"]
        for item in _claims(bundle)["properties"]:
            rows.append(f"| `{bundle}` | {status} | `{item['name']}` | {runtime_check(bundle, item)} |")
    return "\n".join(rows)


def _documented(path: Path) -> str:
    return path.read_text(encoding="utf-8").split(BEGIN, 1)[1].split(END, 1)[0].strip()


def documented_controls(bundle: str) -> set:
    """``(control, property)`` for every "must violate" row of the README's Files table."""

    found = set()
    for line in (ROOT / "formal" / bundle / "README.md").read_text(encoding="utf-8").splitlines():
        row = _CONTROL_ROW.match(line)
        if not row:
            continue
        names = _CONTROL_FILE.findall(row.group("files"))
        properties = re.findall(r"must violate `([A-Za-z]+)`", row.group("holds"))
        assert names and len(properties) == 1, line
        found.update((name, properties[0]) for name in names)
    return found


def claimed_controls(bundle: str) -> set:
    return {(control, item["name"]) for item in _claims(bundle)["properties"] for control in item["negative_controls"]}


def test_the_hand_written_oracle_notes_name_only_claimed_properties():
    claimed = {(bundle, item["name"]) for bundle in BUNDLES for item in _claims(bundle)["properties"]}

    assert set(ORACLE) <= claimed
    assert set(HOW) <= claimed


def test_the_spec_bridge_page_lists_every_property_and_what_checks_it():
    documented = _documented(ROOT / "docs" / "spec-bridge.md")

    assert documented == all_bundles_table(), "regenerate the table:\n" + all_bundles_table()


@pytest.mark.parametrize("bundle", BUNDLES)
def test_each_bundle_readme_lists_its_properties_and_what_checks_them(bundle):
    documented = _documented(ROOT / "formal" / bundle / "README.md")

    assert documented == bundle_table(bundle), "regenerate the table:\n" + bundle_table(bundle)


@pytest.mark.parametrize("bundle", BUNDLES)
def test_each_bundle_readme_names_every_negative_control_with_the_property_it_violates(bundle):
    # The Files table is written by hand; claims.yaml `negative_controls` is what `spec check` runs.
    assert documented_controls(bundle) == claimed_controls(bundle)
    for control, _ in claimed_controls(bundle):
        files = list((ROOT / "formal" / bundle / "negative-controls").glob(f"{control}.*"))
        assert files, (bundle, control)


def test_a_bundle_the_runtime_does_not_check_says_so_in_its_claims():
    # The claims file is the first thing a maintainer reads: it must not suggest a live check that is not there.
    for bundle in BUNDLES:
        text = (ROOT / "formal" / bundle / "claims.yaml").read_text(encoding="utf-8")
        has_runtime_check = any(runtime_check(bundle, item) != MODEL_ONLY for item in _claims(bundle)["properties"])
        assert ("Model only:" in text) == (not has_runtime_check), bundle
