"""Tables in the docs generated from what they list: docs/components/README.md indexes every component and
provider and lists every component's declared events, evidence, and state changes (scripts/gen_component_docs.py
writes both), and docs/bug-zoo.md every bug zoo case.

On a mismatch the assertion message says what to run or holds the table to paste between the markers.
"""

import importlib.util
import sys
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]
ZOO_DOC = ROOT / "docs" / "bug-zoo.md"
ZOO_BEGIN = "<!-- BEGIN cases: generated by tests/test_docs_declarations.py -->"
ZOO_END = "<!-- END cases -->"


def _load_generator():
    spec = importlib.util.spec_from_file_location("gen_component_docs", ROOT / "scripts" / "gen_component_docs.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def generator():
    return _load_generator()


def test_the_component_reference_is_in_step_with_the_catalog(generator, capsys):
    assert generator.main(["--check"]) == 0, capsys.readouterr().out + capsys.readouterr().err


def test_the_component_pages_document_every_catalog_entry(generator):
    assert generator.check_sections(generator._catalog()) == []


def test_the_generator_names_a_component_without_an_index_row(generator):
    text = generator.INDEX.read_text(encoding="utf-8")
    without = text.replace("| [`valkey.action.sleep`](actions.md#valkeyactionsleep) | any | waits |\n", "", 1)
    assert without != text

    with pytest.raises(generator.DocsError, match=r"(?s)no index row for valkey\.action\.sleep.*valkeyactionsleep"):
        generator.render(without)


def test_the_generator_rejects_a_row_the_catalog_lacks(generator):
    text = generator.INDEX.read_text(encoding="utf-8")
    extra = text.replace(
        generator.INDEX_END,
        "| [`valkey.action.gone`](actions.md#valkeyactiongone) | any | nothing |\n" + generator.INDEX_END,
        1,
    )

    with pytest.raises(generator.DocsError, match=r"lists valkey\.action\.gone, which the catalog lacks"):
        generator.render(extra)


def test_the_generator_keeps_a_note_after_the_modes_and_rejects_other_modes(generator):
    text = generator.INDEX.read_text(encoding="utf-8")
    assert "| any (needs `syscall_faults`) |" in generator.render(text)

    wrong = text.replace(
        "[`valkey.action.failover`](actions.md#valkeyactionfailover) | cluster |",
        "[`valkey.action.failover`](actions.md#valkeyactionfailover) | any |",
        1,
    )
    assert wrong != text
    with pytest.raises(generator.DocsError, match=r"valkey\.action\.failover: the modes cell 'any'"):
        generator.render(wrong)


def test_a_section_on_the_wrong_page_is_reported(generator, tmp_path, monkeypatch):
    pages = tmp_path / "components"
    pages.mkdir()
    for page in sorted({page for _, _, page in generator.GROUPS}):
        pages.joinpath(f"{page}.md").write_text("# page\n", encoding="utf-8")
    pages.joinpath("actions.md").write_text("## `valkey.oracle.liveness`\n## `valkey.action.nope`\n", encoding="utf-8")
    monkeypatch.setattr(generator, "DOCS", pages)

    problems = generator.check_sections([("valkey.oracle.liveness", "any"), ("valkey.action.sleep", "any")])

    assert "valkey.oracle.liveness: no `## `valkey.oracle.liveness`` section in docs/components/oracles.md" in problems
    assert "valkey.oracle.liveness: documented in docs/components/actions.md, its page is oracles.md" in problems
    assert "valkey.action.sleep: no `## `valkey.action.sleep`` section in docs/components/actions.md" in problems
    assert "docs/components/actions.md documents valkey.action.nope, which the catalog lacks" in problems


def zoo_table() -> str:
    rows = [
        "| Case | Level | What is broken | What catches it | Broken runs | Must detect |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for case in sorted(path.parent for path in (ROOT / "zoo").glob("*/case.yaml")):
        document = yaml.safe_load((case / "case.yaml").read_text(encoding="utf-8"))
        level = "build" if (case / "patch.diff").exists() else "configuration"
        if document.get("skipped_until"):
            level = f"skipped until {document['skipped_until']}"
        rows.append(
            f"| `{case.name}` | {level} | {document['description']} | {document['catches']} "
            f"| {document['runs']} | {document['min_detection_rate']:.0%} |"
        )
    return "\n".join(rows)


def test_the_bug_zoo_page_lists_every_case():
    text = ZOO_DOC.read_text(encoding="utf-8")
    documented = text.split(ZOO_BEGIN, 1)[1].split(ZOO_END, 1)[0].strip()

    assert documented == zoo_table(), "regenerate the table:\n" + zoo_table()


def test_the_check_runs_as_a_script():
    import subprocess

    result = subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "gen_component_docs.py"), "--check"],
        capture_output=True,
        text=True,
        cwd=ROOT,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    assert "in step with the catalog" in result.stdout
